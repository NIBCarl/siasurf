/**
 * Canonical Siargao surf-break registry.
 *
 * Source: the VAN Surf Camp Siargao surf-spot directory (33 bookable entries
 * across 17 surf locations), reconciled with Siargao's real geography.
 *
 * The 33 entries collapse to 31 distinct breaks:
 *  - Salvacion is published twice (once as North, once as East) — it is one
 *    break on the north-east corner, so it is seeded once, as North.
 *  - Burgos (Outer) is published as both Intermediate and Expert. `difficulty`
 *    records the *minimum* level able to surf the break, so it is seeded as
 *    Intermediate; expert surfers can still book it.
 *  - Giwan (Outer) is tagged Beginner but is also recommended for intermediate
 *    longboarders, so it is seeded as Beginner for the same reason.
 *
 * `area` is the municipality the break actually sits in (Burgos, Dapa, General
 * Luna, Pilar, San Isidro), `barangay` the village, `side` the coast the break
 * works on (North/East/South — the source publishes no West breaks) and
 * `section` the break zone (Inner/Outer). Inner and Outer are the soft and
 * hollow sections of the same reef: they are separate records because they
 * carry different difficulty ratings, but they share a line-up.
 *
 * Coordinates are WGS84. Where Google Maps has a named place for the break
 * ("Salvacion Surf Spot", "Cloud 9 Surf Spot", …) that place pin is used at full
 * precision, so clicking the spot in Google Maps lands exactly on the marker.
 * The remaining breaks use the source directory's coordinates, cross-checked
 * against OpenStreetMap and the Google Plus Codes they publish. `plus_code` is
 * derived from the stored pin, so the two can never disagree. Pins are accurate
 * enough to put a marker on the correct break; SISA can still correct any pin
 * through Admin → Surf Spots without a deploy. That screen, not this file, is
 * the production source of truth.
 *
 * `is_safe_zone` drives FR 3.5: only breaks flagged here can be offered to
 * beginners by the safety engine. Every break the source designates Beginner
 * is flagged, because those are the line-ups instructors actually teach on.
 */
class SurfSpotSeeder extends Seeder
{
    public function run(): void
    {
        $spots = $this->spots();

        foreach ($spots as $index => $spot) {
            SurfSpot::updateOrCreate(
                ['name' => $spot['name']],
                $spot + ['sort_order' => $index]
            );
        }

        // Retire anything from an older seed run that is not in the canonical
        // list. Deactivated rather than deleted so booking history keeps its
        // surf_spot_id.
        SurfSpot::query()
            ->whereNotIn('name', array_column($spots, 'name'))
            ->where('is_active', true)
            ->update(['is_active' => false]);
    }

